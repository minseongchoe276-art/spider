import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import WebSocket from 'ws';
import { attachRooms } from './rooms.mjs';
import { MATCH, policeCount, resolveMatchSpawn, teamOffset } from '../src/MatchRules.js';

assert.equal(policeCount(2),1);
assert.equal(policeCount(3),1);
assert.equal(policeCount(4),1);
assert.equal(policeCount(6),1);
assert.equal(policeCount(7),2);
assert.equal(policeCount(8),2);
const anchor={x:0,y:90.1,z:0};
const supported=()=>90;
const policeSpawn=resolveMatchSpawn(anchor,teamOffset(0,'police',1),supported,[]);
const runnerSpawn=resolveMatchSpawn(anchor,teamOffset(0,'runner',1),supported,[]);
assert.equal(policeSpawn.z,-28);
assert.equal(runnerSpawn.z,28);
assert(Math.hypot(policeSpawn.x-runnerSpawn.x,policeSpawn.z-runnerSpawn.z)>MATCH.web.reach,'Team spawns sit inside one web shot');
const sameSide=resolveMatchSpawn(anchor,{x:0,z:-28},p=>Math.abs(p.z)===30?39.9:NaN,[{x:0,y:40,z:-30},{x:0,y:40,z:30}]);
assert(sameSide.z<0,'Spawn fallback crossed to the other team side');

const server=createServer((req,res)=>res.end('ok'));
const api=attachRooms(server);
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const url=`ws://127.0.0.1:${server.address().port}/ws`;
const sockets=[];
const connect=()=>new Promise((resolve,reject)=>{const ws=new WebSocket(url);ws.events=[];ws.on('message',raw=>ws.events.push(JSON.parse(raw)));ws.once('open',()=>{sockets.push(ws);resolve(ws);});ws.once('error',reject);});
const send=(ws,data)=>ws.send(JSON.stringify(data));
const wait=async(ws,predicate)=>{const end=Date.now()+2500;while(Date.now()<end){const i=ws.events.findIndex(predicate);if(i>=0)return ws.events.splice(i,1)[0];await new Promise(r=>setTimeout(r,10));}throw Error(`Timed out: ${JSON.stringify(ws.events)}`);};
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const quiet=async(ws,ms=300)=>{const mark=ws.events.length;await sleep(ms);return ws.events.slice(mark);};
try {
  MATCH.graceMs=120000;
  const players=await Promise.all(Array.from({length:4},connect));
  send(players[0],{type:'create',name:'여유 방',mode:'tag',capacity:4,city:'procedural',playerName:'호스트'});
  const graceOpen=await wait(players[0],v=>v.type==='room'&&v.room.count===1);
  const graceCode=graceOpen.room.code;
  for(let i=1;i<4;i++)send(players[i],{type:'join',code:graceCode,city:'procedural',playerName:`친구${i}`});
  await wait(players[0],v=>v.type==='room'&&v.room.count===4);
  for(const ws of players)send(ws,{type:'ready',ready:true});
  await wait(players[0],v=>v.type==='room'&&v.players.every(p=>p.ready));
  send(players[0],{type:'start'});
  const graceStart=await wait(players[0],v=>v.type==='room'&&v.room.phase==='playing');
  assert.equal(typeof graceStart.serverNow,'number');
  assert(graceStart.vulnerableAt>graceStart.serverNow,'Opening grace was missing from the room clock');
  const graceIds=await Promise.all(players.map(ws=>wait(ws,v=>v.type==='joined').then(v=>v.id)));
  const gracePolice=players[graceIds.indexOf(graceStart.players.find(p=>p.team==='police').id)];
  const graceRunner=players[graceIds.indexOf(graceStart.players.find(p=>p.team==='runner').id)];
  send(gracePolice,{type:'move',x:0,y:0,z:0,facing:0});send(graceRunner,{type:'move',x:0,y:0,z:2,facing:0});
  await wait(gracePolice,v=>v.type==='move');
  send(gracePolice,{type:'attack',kind:'punch',facing:0});
  assert(!(await quiet(graceRunner)).some(v=>v.type==='hit'),'A punch landed during the opening grace');
  for(const ws of players)send(ws,{type:'leave'});
  await wait(players[0],v=>v.type==='left');
  for(const ws of players)ws.events.length=0;

  MATCH.graceMs=0;
  send(players[0],{type:'create',name:'테스트 방',mode:'tag',capacity:4,city:'procedural',playerName:'호스트'});
  const first=await wait(players[0],v=>v.type==='room'&&v.room.count===1&&v.room.phase==='waiting');
  assert.match(first.room.code,/^[A-F0-9]{6}$/);
  const code=first.room.code;
  for(let i=1;i<4;i++)send(players[i],{type:'join',code,city:'procedural',playerName:`친구${i}`});
  await wait(players[0],v=>v.type==='room'&&v.room.code===code&&v.room.count===4);
  for(const ws of players)send(ws,{type:'ready',ready:true});
  await wait(players[0],v=>v.type==='room'&&v.room.code===code&&v.room.phase==='waiting'&&v.players.every(p=>p.ready));
  send(players[0],{type:'start'});
  const started=await wait(players[0],v=>v.type==='room'&&v.room.phase==='playing'&&v.room.code===code);
  assert.equal(started.players.filter(p=>p.team==='police').length,1);
  assert.equal(started.players.filter(p=>p.team==='runner').length,3);
  assert.equal(typeof started.serverNow,'number');
  assert(started.vulnerableAt<=started.serverNow);
  const ids=await Promise.all(players.map(ws=>wait(ws,v=>v.type==='joined').then(v=>v.id)));
  const policeId=started.players.find(p=>p.team==='police').id;
  const runnerIds=started.players.filter(p=>p.team==='runner').map(p=>p.id);
  const police=players[ids.indexOf(policeId)];
  const runner=players[ids.indexOf(runnerIds[0])];
  const bystander=players[ids.indexOf(runnerIds[1])];
  send(police,{type:'attack',kind:'punch',facing:0});
  assert(!(await quiet(runner,200)).some(v=>v.type==='hit'),'An unseen police punch hit a stacked origin');
  send(police,{type:'move',x:0,y:0,z:0,facing:0});send(runner,{type:'move',x:0,y:0,z:2,facing:0});
  await wait(police,v=>v.type==='move'&&v.id===runnerIds[0]);
  send(runner,{type:'attack',kind:'punch',facing:0});
  assert(!(await quiet(police,200)).some(v=>v.type==='hit'),'A runner attack dealt damage');
  send(police,{type:'attack',kind:'punch',facing:0});
  const hit=await wait(runner,v=>v.type==='hit');
  assert.equal(hit.health,75);
  send(police,{type:'attack',kind:'punch',facing:0});
  assert(!(await quiet(runner,200)).some(v=>v.type==='hit'),'A second punch ignored its cooldown');
  await sleep(580);
  send(runner,{type:'move',x:2,y:0,z:0.5,facing:0});
  await wait(police,v=>v.type==='move'&&v.x===2);
  send(police,{type:'attack',kind:'punch',facing:0});
  assert(!(await quiet(runner,200)).some(v=>v.type==='hit'),'A punch outside the facing cone still hit');
  await sleep(580);
  send(bystander,{type:'move',x:0,y:0,z:10,facing:0});
  await wait(police,v=>v.type==='move'&&v.id===runnerIds[1]);
  send(police,{type:'attack',kind:'web',facing:0});
  const web=await wait(bystander,v=>v.type==='hit'&&v.kind==='web');
  assert.equal(web.health,85);
  send(runner,{type:'move',x:0,y:0,z:2,facing:0});
  await wait(police,v=>v.type==='move'&&v.id===runnerIds[0]&&v.z===2);
  for(const health of [50,25,0]){
    await sleep(580);
    send(police,{type:'attack',kind:'punch',facing:0});
    const next=await wait(runner,v=>v.type==='hit'&&v.kind==='punch'&&v.target===runnerIds[0]);
    assert.equal(next.health,health);
  }
  send(runner,{type:'move',x:3,y:0,z:2,facing:0});
  send(runner,{type:'attack',kind:'punch',facing:0});
  const afterOut=await quiet(police,250);
  assert(!afterOut.some(v=>v.type==='move'&&v.id===runnerIds[0]&&v.x===3),'An eliminated runner still published a move');
  assert(!afterOut.some(v=>v.type==='hit'),'An eliminated runner was hit again');
  api.rooms.get(code).endsAt=Date.now()-1;
  const finished=await wait(players[0],v=>v.type==='room'&&v.room.phase==='finished');
  assert.equal(finished.winner,'runner');
  send(players[3],{type:'join',code,city:'procedural',playerName:'늦은 참가자'});
  await wait(players[3],v=>v.type==='error');

  const seven=await Promise.all(Array.from({length:7},connect));
  send(seven[0],{type:'create',name:'7인 방',mode:'tag',capacity:7,city:'procedural',playerName:'호스트'});
  const sevenOpen=await wait(seven[0],v=>v.type==='room'&&v.room.count===1&&v.room.capacity===7);
  for(let i=1;i<7;i++)send(seven[i],{type:'join',code:sevenOpen.room.code,city:'procedural',playerName:`친구${i}`});
  await wait(seven[0],v=>v.type==='room'&&v.room.count===7);
  for(const ws of seven)send(ws,{type:'ready',ready:true});
  await wait(seven[0],v=>v.type==='room'&&v.players.length===7&&v.players.every(p=>p.ready));
  send(seven[0],{type:'start'});
  const sevenStart=await wait(seven[0],v=>v.type==='room'&&v.room.phase==='playing'&&v.room.capacity===7);
  assert.equal(sevenStart.players.filter(p=>p.team==='police').length,2);

  const pair=await Promise.all([connect(),connect()]);
  send(pair[0],{type:'create',name:'2인 방',mode:'tag',capacity:2,city:'procedural',playerName:'호스트'});
  const pairOpen=await wait(pair[0],v=>v.type==='room'&&v.room.capacity===2&&v.room.count===1);
  send(pair[1],{type:'join',code:pairOpen.room.code,city:'procedural',playerName:'친구'});
  await wait(pair[0],v=>v.type==='room'&&v.room.code===pairOpen.room.code&&v.room.count===2);
  const extra=await connect();
  send(extra,{type:'join',code:pairOpen.room.code,city:'procedural',playerName:'세 번째'});
  const full=await wait(extra,v=>v.type==='error');
  assert.match(full.message,/가득/);
  for(const ws of pair)send(ws,{type:'ready',ready:true});
  await wait(pair[0],v=>v.type==='room'&&v.room.code===pairOpen.room.code&&v.players.length===2&&v.players.every(p=>p.ready));
  send(pair[0],{type:'start'});
  const pairStart=await wait(pair[0],v=>v.type==='room'&&v.room.code===pairOpen.room.code&&v.room.phase==='playing');
  assert.equal(pairStart.players.filter(p=>p.team==='police').length,1);
  assert.equal(pairStart.players.filter(p=>p.team==='runner').length,1);
  send(pair[0],{type:'create',name:'혼자',mode:'tag',capacity:1,city:'procedural',playerName:'호스트'});
  const rejected=await wait(pair[0],v=>v.type==='error');
  assert.match(rejected.message,/2~8/);
  console.log('PASS multiplayer: 4-player room, ready gate, teams, server damage, late join rejection');
} finally {for(const ws of sockets)ws.close();await new Promise(resolve=>server.close(resolve));}
