import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '/Users/choeminseong/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const shotDir = path.join(root, 'docs/qa/quality-director-2026-10-28/shots');
const base = process.env.QUALITY_URL || 'http://127.0.0.1:5191';
const browser = await chromium.launch({ channel: 'chrome', headless: false });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
await page.goto(`${base}/?city=procedural&play=solo&qualityDirector=1`, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => globalThis.__shadowPulseQuality?.playing?.(), null, { timeout: 90000 });
await page.click('#btn-start-drag').catch(() => {});
const aim = await page.evaluate(() => globalThis.__shadowPulseQuality.seekWebTarget());
await page.evaluate(() => globalThis.__shadowPulseQuality.begin('aimed-swing'));
const box = await page.locator('#webgl-canvas').boundingBox();
await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
await page.mouse.down();
await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(shotDir, '08-aimed-swing.png') });
await page.mouse.down({ button: 'right' });
await page.waitForTimeout(700);
await page.screenshot({ path: path.join(shotDir, '09-aimed-dual.png') });
await page.mouse.up();
await page.mouse.up({ button: 'right' });
await page.waitForTimeout(500);
const result = await page.evaluate(() => globalThis.__shadowPulseQuality.end());
const dump = await page.evaluate(() => globalThis.__shadowPulseQuality.dump());
const report = { aim, summary: result.summary, audio: dump.audioCounts, vfx: dump.vfxCounts, errors, samples: result.samples?.filter(sample => sample.swinging || sample.webs.length).slice(0, 12) };
fs.writeFileSync(path.join(root, 'docs/qa/quality-director-2026-10-28/swing-retest.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify({ aim, summary: result.summary, vfx: dump.vfxCounts, audio: dump.audioCounts }, null, 2));
await browser.close();
if (!result.summary.swingingFrames) process.exitCode = 1;
