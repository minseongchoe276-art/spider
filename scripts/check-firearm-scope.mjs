import assert from 'node:assert/strict';
import * as T from 'three';
import {scopedFov,scopedTarget,SCOPE_ZOOMS} from '../src/FirearmScope.js';
import {CombatSystem} from '../src/Combat.js';
import {createTrainingOpponent} from '../src/TrainingOpponent.js';
const camera=new T.PerspectiveCamera(64,1,.1,500);camera.position.set(0,1,0);camera.lookAt(0,1,10);camera.updateProjectionMatrix();camera.updateMatrixWorld(true);
const p=(x,y,z)=>({position:new T.Vector3(x,y,z),health:100});
const origin=new T.Vector3(0,1,0),city={raycast:()=>null};
const near=p(0,0,8),far=p(0,0,16),side=p(2,0,6),high=p(0,3,6);
assert.equal(scopedTarget(camera,origin,[far,side,high,near],30,city)?.target,near);
assert.equal(scopedTarget(camera,origin,[far],10,city),null);
assert.equal(scopedTarget(camera,origin,[side,high],30,city),null);
assert.equal(scopedTarget(camera,origin,[near],30,{raycast:()=>({distance:2})}),null);
assert.equal(scopedTarget(camera,origin,[near],30,{raycast:()=>({distance:20})})?.target,near);
const camera2=camera.clone();camera2.position.set(0,4,0);camera2.lookAt(0,4,10);camera2.updateMatrixWorld(true);
assert.equal(scopedTarget(camera2,new T.Vector3(0,4,0),[high],30,city)?.target,high);
const meshTarget=p(0,0,8);meshTarget.hitRoot=new T.Mesh(new T.SphereGeometry(.2),new T.MeshBasicMaterial());meshTarget.hitRoot.position.set(.5,1,8);
assert.equal(scopedTarget(camera,origin,[meshTarget],30,city),null,'misses inside a broad body box must not hit mesh');
meshTarget.hitRoot.position.x=0;assert.equal(scopedTarget(camera,origin,[meshTarget],30,city)?.target,meshTarget);
const mannequin=createTrainingOpponent('dummy');mannequin.group.position.set(0,0,8);const rigTarget={position:mannequin.group.position,health:100,pose:mannequin.pose};
assert.equal(scopedTarget(camera,origin,[rigTarget],30,city)?.target,rigTarget,'training rig geometry must be hittable');
assert(scopedFov(64,4)<scopedFov(64,2));assert.deepEqual(SCOPE_ZOOMS['sniper-rifle'],[2,4,8]);
const physics={state:'IDLE',position:new T.Vector3(),velocity:new T.Vector3(),facingAngle:0,city};
const combat=new CombatSystem(new T.Scene(),physics,{}, {getTargets:()=>[near,far,side]});combat.mode='combat';combat.gunEquipped=true;camera.userData.firearmScoped=true;
assert(combat.attack(camera));assert.equal(near.health,78);assert.equal(far.health,100);assert.equal(side.health,100);combat.after(.08);assert.equal(near.health,78);
combat.cancel();near.health=100;physics.city={raycast:()=>({distance:2})};assert(combat.attack(camera));assert.equal(near.health,100);
console.log('PASS scoped ray: zoom, elevation, nearest target, range, obstruction and one-shot damage');
